# 假定有一正整数n，其除n自身以外的所有正整数因子的和为m
# （例如，若n为12，则其和为1+2+3+4+6=16），
# 则正整数n必有以下三种情形： 
# m< n，亏数，2、3、4、5、7、8、9、10、... 
# m =n，完美数，6、28、496、... 
# m >n，盈数，12、18、20、24、30、.. 
# 求1000以内的完美数。
result =[]
for n in range(1, 1001):
    m = 0
    for j in range(1, n):
        if n % j == 0:
            m = m + j
    if m == n:
        result.append(n)
a = " ".join(map(str, result))
print(f"1000以内的完美数:{a}")

